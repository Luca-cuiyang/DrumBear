#!/usr/bin/env python3
"""Extract a rhythm-authoritative drum score from Audiveris MusicXML.

The MusicXML must be generated by Audiveris from the source image.  It is not
an external input score; this module uses its sequential duration timeline to
avoid re-guessing note onsets from horizontal pixel spacing.
"""

from __future__ import annotations

import argparse
import json
import re
import zipfile
from collections import defaultdict
from fractions import Fraction
from pathlib import Path
from xml.etree import ElementTree as ET


DRUM_NAMES = {
    "Acoustic_Bass_Drum": 35,
    "Bass_Drum_1": 36,
    "Side_Stick": 37,
    "Acoustic_Snare": 38,
    "Hand_Clap": 39,
    "Electric_Snare": 40,
    "Low_Floor_Tom": 41,
    "Closed_Hi_Hat": 42,
    "High_Floor_Tom": 43,
    "Pedal_Hi_Hat": 44,
    "Low_Tom": 45,
    "Open_Hi_Hat": 46,
    "Low_Mid_Tom": 47,
    "Hi_Mid_Tom": 48,
    "Crash_Cymbal_1": 49,
    "High_Tom": 50,
    "Ride_Cymbal_1": 51,
    "Chinese_Cymbal": 52,
    "Ride_Bell": 53,
    "Tambourine": 54,
    "Splash_Cymbal": 55,
    "Cowbell": 56,
    "Crash_Cymbal_2": 57,
    "Vibraslap": 58,
    "Ride_Cymbal_2": 59,
}

ARTICULATIONS = {
    "accent": "accent",
    "staccato": "staccato",
    "staccatissimo": "staccatissimo",
    "tenuto": "tenuto",
}


def read_musicxml(path: Path) -> ET.Element:
    with zipfile.ZipFile(path) as archive:
        candidates = [
            name
            for name in archive.namelist()
            if name.endswith((".xml", ".musicxml"))
            and not name.startswith("META-INF/")
        ]
        if len(candidates) != 1:
            raise ValueError(f"Expected one MusicXML root in {path}, got {candidates}")
        return ET.fromstring(archive.read(candidates[0]))


def instrument_map(
    root: ET.Element,
    *,
    dbscore_export: bool = False,
) -> dict[str, int]:
    result: dict[str, int] = {}
    for score_part in root.findall("./part-list/score-part"):
        for instrument in score_part.findall("score-instrument"):
            instrument_id = instrument.get("id", "")
            if dbscore_export:
                match = re.fullmatch(r"P\d+-I(\d+)", instrument_id)
                if match:
                    # DB Score's MusicXML exporter numbers drum instruments
                    # from 36 while preserving the zero-based source pitch.
                    result[instrument_id] = int(match.group(1)) - 1
                    continue
            name = instrument.findtext("instrument-name", "").strip()
            normalized_name = name.replace(" ", "_").replace("-", "_")
            pitch = DRUM_NAMES.get(normalized_name)
            if pitch is not None:
                result[instrument_id] = pitch
    return result


def parse_lengths(spec: str) -> dict[int, int]:
    lengths: dict[int, int] = {}
    for item in spec.split(","):
        if not item:
            continue
        numbers, beats_text = item.split(":")
        beats = int(beats_text)
        if "-" in numbers:
            first, last = numbers.split("-", 1)
            for number in range(int(first), int(last) + 1):
                lengths[number] = beats
        else:
            lengths[int(numbers)] = beats
    return lengths


def duration_type(note: ET.Element) -> str:
    value = note.findtext("type")
    if value:
        return value
    duration = int(note.findtext("duration") or 0)
    return {
        1920: "half",
        960: "quarter",
        480: "eighth",
        240: "16th",
        120: "32nd",
        60: "64th",
    }.get(duration, "quarter")


def extract_page(
    path: Path,
    title: str,
    tempo: int,
    lengths: dict[int, int],
    *,
    dbscore_export: bool = False,
) -> dict:
    root = read_musicxml(path)
    instruments = instrument_map(root, dbscore_export=dbscore_export)
    if not instruments:
        raise ValueError(
            "当前 AI 转谱仅支持架子鼓鼓谱；MusicXML 中没有可识别的鼓组乐器"
        )
    parts = root.findall("./part")
    if len(parts) != 1:
        raise ValueError(f"Expected one drum part in {path}, got {len(parts)}")

    payload = {
        "title": title,
        "tempo": tempo,
        "measure_count": 0,
        "unknown_heads": [],
        "measures": [],
    }
    divisions = Fraction(1)
    for measure_number, measure in enumerate(parts[0].findall("measure"), 1):
        divisions_text = measure.findtext("./attributes/divisions")
        if divisions_text:
            divisions = Fraction(int(divisions_text))

        attributes = measure.find("attributes")
        beats = lengths.get(measure_number, 4)
        if attributes is not None:
            beats_text = attributes.findtext("./time/beats")
            beat_type = attributes.findtext("./time/beat-type")
            if beats_text and beat_type and Fraction(beats_text) == Fraction(
                int(beat_type), 4
            ):
                beats = int(beats_text)

        voice_cursors: dict[str, int] = defaultdict(int)
        last_onsets: dict[str, int] = defaultdict(int)
        events: dict[tuple[int], dict] = {}
        rests: list[dict] = []
        beam_open: dict[str, str] = {}
        beam_counter = 0
        for element in list(measure):
            if element.tag in {"backup", "forward"}:
                continue
            if element.tag != "note":
                continue

            duration = int(element.findtext("duration") or 0)
            if duration <= 0:
                continue
            is_chord = element.find("chord") is not None
            voice = element.findtext("voice", "1")
            onset = last_onsets[voice] if is_chord else voice_cursors[voice]
            if not is_chord:
                last_onsets[voice] = onset
                voice_cursors[voice] += duration

            if element.find("rest") is not None:
                rests.append(
                    {
                        "time": str(Fraction(onset, int(divisions) * 4)),
                        "voice": "down" if voice == "2" else "up",
                        "duration": duration_type(element),
                        "dots": len(element.findall("dot")),
                        "review": False,
                        "source": "audiveris-musicxml-rest",
                    }
                )
                continue

            beam_value = element.findtext("./beam[@number='1']")
            beam_group = beam_open.get(voice)
            if beam_value == "begin":
                beam_counter += 1
                beam_group = f"mxl:{measure_number}:{voice}:{beam_counter}"
                beam_open[voice] = beam_group
            elif beam_value == "end":
                beam_open.pop(voice, None)

            instrument_element = element.find("instrument")
            instrument = (
                instrument_element.get("id", "")
                if instrument_element is not None
                else ""
            )
            pitch = instruments.get(instrument)
            if pitch is None:
                raise ValueError(
                    f"Measure {measure_number}: unknown drum instrument {instrument!r}"
                )

            key = (onset,)
            event = events.setdefault(
                key,
                {
                    "time": str(Fraction(onset, int(divisions) * 4)),
                    "x": float(element.get("default-x", 0)),
                    "rhythm_x": float(element.get("default-x", 0)),
                    "pitches": [],
                    "parts": [],
                    "articulations": [],
                    "review": False,
                    "time_verified": True,
                    "source": "audiveris-musicxml",
                },
            )
            event["pitches"] = sorted(set(event["pitches"] + [pitch]))
            part = next(
                (
                    item
                    for item in event["parts"]
                    if item["voice"] == element.findtext("stem", "up")
                ),
                None,
            )
            if part is None:
                part = {
                    "voice": element.findtext("stem", "up") or "up",
                    "pitches": [],
                    "duration": duration_type(element),
                    "dots": len(element.findall("dot")),
                    "beams": len(element.findall("beam")),
                    "beam_group": beam_group,
                }
                event["parts"].append(part)
            part["pitches"] = sorted(set(part["pitches"] + [pitch]))

            for articulation in element.findall("./notations/articulations/*"):
                kind = ARTICULATIONS.get(articulation.tag)
                if kind and kind not in event["articulations"]:
                    event["articulations"].append(kind)

        normalized = []
        for event in events.values():
            for part in event["parts"]:
                part["pitches"].sort()
            event["pitches"].sort()
            normalized.append(event)
        normalized.sort(key=lambda event: (Fraction(event["time"]), event["x"]))
        bar_end = Fraction(beats, 4)
        for event in normalized:
            if Fraction(event["time"]) >= bar_end:
                event["time"] = str(bar_end - Fraction(1, 16))
                event["review"] = True
                event["review_resolution"] = "musicxml-closing-barline"

        start_repeat = any(
            element.get("location", "left") == "left"
            and element.find("./repeat") is not None
            and element.find("./repeat").get("direction") == "forward"
            for element in measure.findall("barline")
        )
        end_repeat = any(
            element.get("location", "right") == "right"
            and element.find("./repeat") is not None
            and element.find("./repeat").get("direction") == "backward"
            for element in measure.findall("barline")
        )
        payload["measures"].append(
            {
                "number": measure_number,
                "length": beats,
                "system_start": (
                    measure_number == 1
                    or measure.find("print") is not None
                    and measure.find("print").get("new-system") == "yes"
                ),
                "start_repeat": start_repeat,
                "end_repeat": end_repeat,
                "volta": None,
                "events": normalized,
                "rests": rests,
                "slots": [],
            }
        )
    payload["measure_count"] = len(payload["measures"])
    return payload


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("musicxml", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--title", required=True)
    parser.add_argument("--tempo", type=int, required=True)
    parser.add_argument("--lengths", required=True)
    args = parser.parse_args()
    payload = extract_page(
        args.musicxml,
        args.title,
        args.tempo,
        parse_lengths(args.lengths),
    )
    args.output.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"Wrote {args.output}: {len(payload['measures'])} measures")


if __name__ == "__main__":
    main()
